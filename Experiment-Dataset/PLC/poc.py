import serial

ser = serial.Serial('/dev/ttyACM0', 19200)

if ser.isOpen():                        # 判断串口是否成功打开
    print("打开串口成功。")
    print(ser.name)    # 输出串口号
else:
    print("打开串口失败。")

poc = [0x1, 0x1, 0x25, 0x25, 0xb, 0xa0, 0xaf, 0xa0, 0xaf, 0xa0, 0xa0, 0xa0, 
       0xa0, 0xa0, 0xa0, 0xa0, 0xa0, 0xa0, 0xa0, 0xaf, 0x31]

for i in poc:
    ser.write(bytes([i]))

